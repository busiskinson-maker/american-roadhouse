// Generates assets/js/env.js from environment variables or a local .env file.
// Usage: node scripts/build-env.mjs
// The static site has no bundler, so this is how env vars reach the browser.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const fromFile = {};
const envPath = resolve(root, '.env');
if (existsSync(envPath)) {
  for (const line of readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !line.trim().startsWith('#')) fromFile[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}
const get = (k) => process.env[k] || fromFile[k] || '';

if (get('SUPABASE_SERVICE_ROLE_KEY') || /service_role/i.test(get('SUPABASE_ANON_KEY'))) {
  console.error('Refusing to build: a service-role key must never be used in frontend code.');
  process.exit(1);
}
const url = get('SUPABASE_URL');
const key = get('SUPABASE_ANON_KEY');
if (!url || !key) {
  console.error('SUPABASE_URL and SUPABASE_ANON_KEY are required (set them in .env or the environment).');
  process.exit(1);
}
// A JWT-style key whose payload says service_role is also rejected.
try {
  const payload = JSON.parse(Buffer.from(key.split('.')[1] || '', 'base64url').toString());
  if (payload.role === 'service_role') throw new Error('service_role');
} catch (e) {
  if (e.message === 'service_role') {
    console.error('Refusing to build: this is a service_role key, not an anon key.');
    process.exit(1);
  }
}
if (key.startsWith('sb_secret_')) {
  console.error('Refusing to build: this is a secret key, not a publishable key.');
  process.exit(1);
}

writeFileSync(
  resolve(root, 'assets/js/env.js'),
  `// Generated by scripts/build-env.mjs - do not edit or commit.\nwindow.__ENV = ${JSON.stringify({ SUPABASE_URL: url, SUPABASE_ANON_KEY: key })};\n`
);
console.log('Wrote assets/js/env.js');
